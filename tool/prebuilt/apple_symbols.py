"""Generate/check the iOS link roots from the actual Dart FFI lookup surface."""

import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / (
    "packages/cindel_flutter_libs/ios/cindel_flutter_libs/Sources/"
    "cindel_flutter_libs/CindelNativeRetention.c"
)


def ffi_symbols():
    source = (ROOT / "packages/cindel/lib/src/native/dynamic_functions.dart").read_text()
    symbols = sorted(set(re.findall(r"'(cindel_[a-z0-9_]+)'", source)))
    if not symbols or "cindel_abi_version" not in symbols:
        raise RuntimeError("Could not extract Cindel's FFI entrypoints")
    return symbols


def retention_source():
    symbols = ffi_symbols()
    # These opaque declarations take addresses only; no function is called
    # through this table. Actual call signatures remain in the Dart bindings.
    return (
        "// Generated by tool/prebuilt/apple_symbols.py; do not edit.\n"
        "// Link roots for every Dart FFI symbol, including Release dead stripping.\n"
        + "".join(f"extern void {symbol}(void);\n" for symbol in symbols)
        + "\nstatic void (*volatile const cindel_symbols[])(void) = {\n"
        + "".join(f"  &{symbol},\n" for symbol in symbols)
        + "};\n\nvoid CindelRetainNativeSymbols(void) {\n"
        "  // Read every entry: optimizers must not shrink the table to its first item.\n"
        "  for (unsigned i = 0; i < sizeof(cindel_symbols) / sizeof(cindel_symbols[0]); ++i) {\n"
        "    (void)cindel_symbols[i];\n"
        "  }\n}\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = retention_source()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit("Stale iOS FFI link roots; run python tool/prebuilt/apple_symbols.py")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Verified {len(ffi_symbols())} iOS FFI link roots")
